import axios from 'axios';

export default {
  aliases: ['flux', 'dalle', 'diffusion'],
  execute: async ({ sock, m, from, args }) => {
    const prompt = args.join(' ');
    if (!prompt) return sock.sendMessage(from, { text: '❌ Please provide a prompt. E.g., .imagine a cyberpunk city at night' }, { quoted: m });

    await sock.sendMessage(from, { text: `🎨 Generating image for: *${prompt}*...\n(This may take 10-20 seconds)` }, { quoted: m });

    try {
      // Using Pollinations Image API (Free, no key required)
      const imageUrl = `https://image.pollinations.ai/prompt/${encodeURIComponent(prompt)}?width=1024&height=1024&nologo=true`;
      
      const res = await axios.get(imageUrl, { responseType: 'arraybuffer' });
      const buffer = Buffer.from(res.data, 'binary');

      await sock.sendMessage(from, { 
        image: buffer, 
        caption: `🎨 *Prompt:* ${prompt}\n> Generated by XYPHER-X` 
      }, { quoted: m });

    } catch (e) {
      await sock.sendMessage(from, { text: `❌ Image Generation Failed: ${e.message}` }, { quoted: m });
    }
  },
};
