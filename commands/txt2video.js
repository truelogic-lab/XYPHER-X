import axios from 'axios';

export default {
  aliases: ['sora'],
  execute: async ({ sock, m, from, args }) => {
    const prompt = args.join(' ');
    if (!prompt) return sock.sendMessage(from, { text: '❌ Provide a prompt for the video.' }, { quoted: m });

    await sock.sendMessage(from, { text: `🎬 Generating video for: *${prompt}*...\n(This takes time and might fail if the API is busy)` }, { quoted: m });

    try {
      // Free AI video generators usually require API keys or have strict limits.
      // Using a placeholder free API for demonstration.
      const apiUrl = `https://api.ryzendesu.vip/api/ai/txt2video?prompt=${encodeURIComponent(prompt)}`;
      const { data } = await axios.get(apiUrl);

      if (!data || !data.url) throw new Error('Video generation failed or API limit reached.');

      await sock.sendMessage(from, { 
        video: { url: data.url }, 
        caption: `🎬 *Prompt:* ${prompt}\n> Generated by XYPHER-X` 
      }, { quoted: m });

    } catch (e) {
      await sock.sendMessage(from, { text: `❌ Video Generation Failed: ${e.message}` }, { quoted: m });
    }
  },
};
